number = int(input('Введи число: '))
suma = number + 3
print(f'Ти ввів число: {number}, а після додавання 3 отримаємо: {suma}')
dobutok = number * 2
print(f'Ти ввів число: {number}, а після множення на 2 отримаємо: {dobutok}')
riznytsya = number - 5
print(f'Ти ввів число: {number}, а після віднімання 5 отримаємо: {riznytsya}')
chastka = number / 4
print(f'Ти ввів число: {number}, а після ділення на 4 отримаємо: {chastka}')