# --- ЕПІЧНИЙ МАГАЗИН ЗІЛЛЯ ---
# 1. Задаємо стартові значення (це числа int, бо без лапок!)
player_gold = 100
potion_price = 25
# 2. Питаємо ім'я гравця (input повертає текст str, для імені це ідеально)
player_name = input("Привіт, мандрівнику! Як тебе звати? ")
# 3. Використовуємо наші улюблені f-рядки для красивого вітання!
print(f"Вітаю в моєму магазині, {player_name}!")
print(f"У твоєму гаманці зараз є {player_gold} монет золота.")
# 4. Питаємо, скільки зілля гравець хоче купити
# ВАЖЛИВО: одразу загортаємо input() всередину int(), щоб перетворити текст на число!
potions_to_buy = int(input("Скільки зілля здоров'я хочеш купити? "))
# 5. Базова математика: рахуємо загальну вартість та залишок золота
total_cost = potions_to_buy * potion_price
remaining_gold = player_gold - total_cost
# 6. Видаємо чек через f-рядок — без жодних плюсів чи str()! Легко і красиво
print(f"Успішно! Ти купив {potions_to_buy} шт. зілля і витратив {total_cost} золота.")
print(f"Залишок в гаманці: {remaining_gold} монет.")